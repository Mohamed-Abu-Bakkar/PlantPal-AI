import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
  fields: defineTable({
    userId: v.string(),
    name: v.string(),
    location: v.object({ latitude: v.number(), longitude: v.number() }),
    address: v.optional(v.string()),
    soilType: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_user_and_created", ["userId", "createdAt"]),
  iotDevices: defineTable({
    userId: v.string(),
    fieldId: v.id("fields"),
    deviceName: v.string(),
    deviceCode: v.string(),
    status: v.string(),
    lastSeenAt: v.optional(v.number()),
    createdAt: v.number(),
  }).index("by_device_code", ["deviceCode"]).index("by_field", ["fieldId"]).index("by_user", ["userId"]),
  sensorReadings: defineTable({
    userId: v.string(),
    fieldId: v.id("fields"),
    deviceId: v.id("iotDevices"),
    readingId: v.string(),
    soilTemperatureC: v.number(),
    airTemperatureC: v.optional(v.number()),
    airHumidity: v.number(),
    recordedAt: v.number(),
    receivedAt: v.number(),
  }).index("by_field_and_time", ["fieldId", "recordedAt"]).index("by_device_and_time", ["deviceId", "recordedAt"]).index("by_device_and_received", ["deviceId", "receivedAt"]).index("by_reading_id", ["readingId"]),
  plants: defineTable({
    ownerId: v.optional(v.string()),
    name: v.string(),
    species: v.optional(v.string()),
    location: v.optional(v.string()),
    plantedAt: v.optional(v.number()),
    notes: v.optional(v.string()),
    imageStorageId: v.optional(v.id("_storage")),
    createdAt: v.number(),
  })
    .index("by_created", ["createdAt"])
    .index("by_owner_and_created", ["ownerId", "createdAt"]),
  careTasks: defineTable({
    ownerId: v.optional(v.string()),
    plantId: v.optional(v.id("plants")),
    title: v.string(),
    dueAt: v.number(),
    completed: v.boolean(),
    category: v.string(),
  })
    .index("by_due", ["dueAt"])
    .index("by_owner_and_due", ["ownerId", "dueAt"]),
  scanHistory: defineTable({
    ownerId: v.string(),
    plantName: v.string(),
    scientificName: v.optional(v.string()),
    confidence: v.optional(v.number()),
    visibleClues: v.array(v.string()),
    caveats: v.array(v.string()),
    imageStorageId: v.optional(v.id("_storage")),
    createdAt: v.number(),
  }).index("by_owner_and_created", ["ownerId", "createdAt"]),
  chatMessages: defineTable({
    ownerId: v.string(),
    role: v.union(v.literal("user"), v.literal("assistant")),
    content: v.string(),
    createdAt: v.number(),
  }).index("by_owner_and_created", ["ownerId", "createdAt"]),
  suitabilitySearches: defineTable({
    ownerId: v.string(),
    plantName: v.string(),
    location: v.optional(v.string()),
    result: v.optional(v.string()),
    score: v.optional(v.number()),
    notes: v.optional(v.string()),
    createdAt: v.number(),
  }).index("by_owner_and_created", ["ownerId", "createdAt"]),
  healthAssessments: defineTable({
    ownerId: v.string(),
    plantId: v.optional(v.id("plants")),
    plantName: v.string(),
    issue: v.string(),
    confidence: v.optional(v.number()),
    symptoms: v.array(v.string()),
    recommendations: v.array(v.string()),
    imageStorageId: v.optional(v.id("_storage")),
    createdAt: v.number(),
  }).index("by_owner_and_created", ["ownerId", "createdAt"]),
  cartItems: defineTable({
    ownerId: v.string(),
    productKey: v.string(),
    name: v.string(),
    price: v.string(),
    emoji: v.string(),
    quantity: v.number(),
    updatedAt: v.number(),
  }).index("by_owner_and_product", ["ownerId", "productKey"]),
  userPreferences: defineTable({
    ownerId: v.string(),
    locationLabel: v.optional(v.string()),
    preferredUnits: v.optional(v.string()),
    notificationsEnabled: v.optional(v.boolean()),
    updatedAt: v.number(),
  }).index("by_owner", ["ownerId"]),
  supplyCatalog: defineTable({
    productKey: v.string(),
    name: v.string(),
    description: v.string(),
    price: v.string(),
    category: v.string(),
    emoji: v.string(),
    imageStorageId: v.optional(v.id("_storage")),
    createdBy: v.string(),
    updatedBy: v.string(),
    updatedAt: v.number(),
  }).index("by_category", ["category"]).index("by_product_key", ["productKey"]),
  supplyCatalogAudit: defineTable({
    productId: v.id("supplyCatalog"),
    actorId: v.string(),
    action: v.union(v.literal("created"), v.literal("updated"), v.literal("deleted")),
    snapshot: v.string(),
    createdAt: v.number(),
  }).index("by_product_and_created", ["productId", "createdAt"]),
  plantCatalog: defineTable({
    commonName: v.string(), scientificName: v.string(), summary: v.string(), sunlight: v.string(), watering: v.string(), soil: v.string(), temperature: v.string(), emoji: v.string(), updatedAt: v.number(),
  }).index("by_common_name", ["commonName"]),
});
